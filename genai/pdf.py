"""One-page PDF export of an approved draft (section 7.5), with an HTML fallback if reportlab is missing."""

from __future__ import annotations

import html
import io
import json
from datetime import datetime, timezone

try:
    from datetime import UTC
except ImportError:
    UTC = timezone.utc  # type: ignore
from functools import lru_cache
from pathlib import Path
from typing import Any

from common.config import get_settings
from common.schemas import DraftResult

DRAFT_LABEL = "DRAFT — synthetic demo data — requires reporter completion"
TBC = "To be completed by reporter"


@lru_cache(maxsize=1)
def form_fields() -> dict[str, Any]:
    return json.loads((get_settings().data_dir / "pvpi_form_fields.json").read_text(encoding="utf-8"))


def _rows(draft: DraftResult) -> list[tuple[str, list[tuple[str, str | None]]]]:
    report = draft.report.model_dump()
    out = []
    for sec in form_fields()["sections"]:
        value = report.get(sec["key"])
        items = value if isinstance(value, list) else [value or {}]
        for n, item in enumerate(items or [{}]):
            title = sec["title"] + (f" ({n + 1})" if len(items) > 1 else "")
            out.append((title, [(f["label"], (item or {}).get(f["key"])) for f in sec["fields"]]))
    return out


def _ascii(s: str) -> str:
    """Base-14 PDF fonts cover WinAnsi only; replace the few symbols we may emit."""
    return s.replace("∞", "inf").replace("≥", ">=").replace("≤", "<=")


def render_pdf(draft: DraftResult, alert_meta: dict[str, Any]) -> bytes:
    try:
        from reportlab.lib import colors
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
        from reportlab.lib.units import mm
        from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle
    except ImportError:  # fallback
        return render_html(draft, alert_meta).encode("utf-8")

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=14 * mm, rightMargin=14 * mm, topMargin=12 * mm,
                            bottomMargin=12 * mm, title="PvPI ADR draft", author="CASCADE (draft)")
    ss = getSampleStyleSheet()
    small = ParagraphStyle("small", parent=ss["Normal"], fontSize=7.5, leading=9)
    body = ParagraphStyle("body", parent=ss["Normal"], fontSize=8.5, leading=11)
    banner = ParagraphStyle("banner", parent=ss["Normal"], fontSize=10, leading=13,
                            textColor=colors.HexColor("#b00020"), fontName="Helvetica-Bold")
    h = ParagraphStyle("h", parent=ss["Heading4"], fontSize=9.5, leading=12, spaceBefore=4, spaceAfter=2)
    esc = lambda s: html.escape(_ascii(str(s)))  # noqa: E731
    story: list[Any] = [Paragraph(esc(DRAFT_LABEL), banner),
                        Paragraph(f"Suspected ADR report draft for alert {esc(draft.alert_id)}", ss["Title"]),
                        Paragraph(esc(f"Generator: {draft.generator}; validator: "
                                      f"{'passed' if draft.validator_pass else 'FAILED'}; approved "
                                      f"{alert_meta.get('approved_ts', '')}"), small),
                        Spacer(1, 3 * mm), Paragraph("Note to prescriber", h), Paragraph(esc(draft.note_text), body)]
    for title, fields in _rows(draft):
        story.append(Paragraph(esc(title), h))
        data = [[Paragraph(esc(lbl), small),
                 Paragraph(esc(v) if v not in (None, "") else f"<font color='#8a5a00'><i>{TBC}</i></font>", small)]
                for lbl, v in fields]
        t = Table(data, colWidths=[60 * mm, 120 * mm])
        style = [("GRID", (0, 0), (-1, -1), 0.25, colors.HexColor("#c8ccd2")), ("VALIGN", (0, 0), (-1, -1), "TOP"),
                 ("TOPPADDING", (0, 0), (-1, -1), 1.5), ("BOTTOMPADDING", (0, 0), (-1, -1), 1.5)]
        style += [("BACKGROUND", (1, i), (1, i), colors.HexColor("#fff4d6")) for i, (_, v) in enumerate(fields)
                  if v in (None, "")]
        t.setStyle(TableStyle(style))
        story.append(t)
    story += [Spacer(1, 2 * mm), Paragraph(esc(
        "Generated by CASCADE from synthetic data. Not a medical device. A pharmacist reviewed and approved this "
        "draft; the reporter must complete and check every field before submission. Nothing is sent automatically."),
        small)]
    doc.build(story, onFirstPage=lambda c, d: _footer(c, d), onLaterPages=lambda c, d: _footer(c, d))
    return buf.getvalue()


def _footer(canvas: Any, doc: Any) -> None:
    canvas.saveState()
    canvas.setFont("Helvetica", 7)
    canvas.drawString(doc.leftMargin, 7 * 2.83465, f"{DRAFT_LABEL}   |   page {doc.page}")
    canvas.restoreState()


def page_count(pdf: bytes) -> int:
    return pdf.count(b"/Type /Page") - pdf.count(b"/Type /Pages")


def render_html(draft: DraftResult, alert_meta: dict[str, Any]) -> str:
    rows = "".join(
        f"<h3>{html.escape(title)}</h3><table>" + "".join(
            f"<tr><th>{html.escape(lbl)}</th><td class='{'tbc' if v in (None, '') else ''}'>"
            f"{html.escape(str(v)) if v not in (None, '') else TBC}</td></tr>" for lbl, v in fields) + "</table>"
        for title, fields in _rows(draft))
    return (f"<!doctype html><meta charset='utf-8'><title>PvPI draft {html.escape(draft.alert_id)}</title>"
            "<style>body{font:13px system-ui;margin:24px}.tbc{background:#fff4d6;font-style:italic}"
            "th{text-align:left;width:40%}td,th{border:1px solid #ccc;padding:3px}</style>"
            f"<p style='color:#b00020;font-weight:bold'>{DRAFT_LABEL}</p><h2>Note to prescriber</h2>"
            f"<p>{html.escape(draft.note_text)}</p>{rows}"
            f"<p><small>Exported {datetime.now(UTC).isoformat()}</small></p>")


def save(pdf: bytes, path: Path) -> None:
    path.write_bytes(pdf)
